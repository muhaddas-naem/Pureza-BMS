// Flattened list of all thanas in Bangladesh
export const allBdThanas: ThanaItem[] = Object.values(bdThanasData).flat();

// Lookup helper for a given district
export function getThanasByDistrict(districtName: string): ThanaItem[] {
  if (!districtName || !districtName.trim()) {
    return allBdThanas;
  }
  const clean = districtName.trim().toLowerCase();

  // Try direct Bengali key
  for (const [distBn, thanas] of Object.entries(bdThanasData)) {
    if (distBn.toLowerCase() === clean || distBn.includes(clean) || clean.includes(distBn.toLowerCase())) {
      return thanas;
    }
    // Match English district name
    if (thanas[0]?.districtEn.toLowerCase() === clean || thanas[0]?.districtEn.toLowerCase().includes(clean)) {
      return thanas;
    }
  }

  return allBdThanas;
}

// Search Thanas supporting both Bangla and English query, scoped to a district if provided
export function searchThanas(query: string, districtName?: string): ThanaItem[] {
  const baseList = districtName ? getThanasByDistrict(districtName) : allBdThanas;
  if (!query || !query.trim()) {
    return baseList;
  }

  const q = query.trim().toLowerCase();

  return baseList.filter((item) => {
    if (item.bn.toLowerCase().includes(q)) return true;
    if (item.en.toLowerCase().includes(q)) return true;
    if (item.altEn && item.altEn.some((alt) => alt.toLowerCase().includes(q))) return true;
    if (item.districtBn.toLowerCase().includes(q)) return true;
    if (item.districtEn.toLowerCase().includes(q)) return true;
    return false;
  });
}
